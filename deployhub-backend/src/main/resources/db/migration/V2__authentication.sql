-- Milestone 3: real accounts and an audit trail. Additive only: no existing data is dropped.

ALTER TABLE users ADD (
    password_hash  VARCHAR2(100),
    status         VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE,
    last_login_at  TIMESTAMP(6) WITH TIME ZONE
);

-- Rows created before this migration (the old development user) have no password, so nobody can
-- log in as them. Mark them so it's explicit rather than accidental.
UPDATE users SET status = 'LEGACY_NO_PASSWORD', updated_at = created_at WHERE password_hash IS NULL;

ALTER TABLE users MODIFY (updated_at NOT NULL);

ALTER TABLE users ADD CONSTRAINT ck_users_status
    CHECK (status IN ('ACTIVE', 'DISABLED', 'LEGACY_NO_PASSWORD'));

-- Emails are stored normalised (trimmed, lower-case); the database enforces that too.
ALTER TABLE users ADD CONSTRAINT ck_users_email_lower CHECK (email = LOWER(email));

CREATE TABLE audit_events (
    id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type   VARCHAR2(40) NOT NULL,
    user_id      NUMBER(19),
    subject      VARCHAR2(254),
    ip_address   VARCHAR2(45),
    details      VARCHAR2(500),
    occurred_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
);

-- Login throttling counts recent failures by (subject, ip) and by ip.
CREATE INDEX ix_audit_type_subject_time ON audit_events (event_type, subject, occurred_at);
CREATE INDEX ix_audit_type_ip_time ON audit_events (event_type, ip_address, occurred_at);
CREATE INDEX ix_audit_user ON audit_events (user_id);
