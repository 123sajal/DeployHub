-- Written to run on both Oracle (19c/23ai) and H2 in MODE=Oracle.

CREATE TABLE users (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR2(255) NOT NULL,
    display_name  VARCHAR2(100) NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE projects (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        NUMBER(19) NOT NULL,
    name            VARCHAR2(50) NOT NULL,
    repository_url  VARCHAR2(300) NOT NULL,
    branch          VARCHAR2(100) NOT NULL,
    app_type        VARCHAR2(30) NOT NULL,
    build_command   VARCHAR2(500),
    start_command   VARCHAR2(500) NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version         NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_projects_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT uk_projects_owner_name UNIQUE (owner_id, name)
);

CREATE TABLE deployments (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      NUMBER(19) NOT NULL,
    status          VARCHAR2(20) NOT NULL,
    execution_mode  VARCHAR2(20) NOT NULL,
    commit_ref      VARCHAR2(100),
    failure_reason  VARCHAR2(1000),
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status_changed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    started_at      TIMESTAMP(6) WITH TIME ZONE,
    finished_at     TIMESTAMP(6) WITH TIME ZONE,
    version         NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_deployments_project FOREIGN KEY (project_id) REFERENCES projects (id)
);

CREATE INDEX ix_deployments_project_created ON deployments (project_id, created_at);
CREATE INDEX ix_deployments_status ON deployments (status);

CREATE TABLE deployment_logs (
    id             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deployment_id  NUMBER(19) NOT NULL,
    log_level      VARCHAR2(10) NOT NULL,
    message        VARCHAR2(4000) NOT NULL,
    occurred_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_logs_deployment FOREIGN KEY (deployment_id) REFERENCES deployments (id)
);

-- Cursor pagination reads "logs for deployment X with id > cursor ORDER BY id".
CREATE INDEX ix_logs_deployment_id ON deployment_logs (deployment_id, id);
