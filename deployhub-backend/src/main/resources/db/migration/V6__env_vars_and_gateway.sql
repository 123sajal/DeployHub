-- Environment variables, a fixed address per project, and routing between projects. Additive only.

-- Per-project settings passed to the app at runtime. Values are encrypted by the application
-- (AES-256-GCM, key outside the database); the plain value is never stored or returned.
CREATE TABLE project_env_vars (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id       NUMBER(19) NOT NULL,
    name             VARCHAR2(100) NOT NULL,
    value_encrypted  VARCHAR2(4000) NOT NULL,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_env_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT uk_env_project_name UNIQUE (project_id, name)
);

-- The project's fixed address on this machine (http://localhost:<public_port>), allocated on first go-live.
ALTER TABLE projects ADD (public_port NUMBER(5));
CREATE UNIQUE INDEX uk_projects_public_port ON projects (public_port);

-- The port the app listens on inside its container, as it was when this deployment went live.
ALTER TABLE deployments ADD (container_port NUMBER(5));

-- Path prefixes of a project's address that go to another project's live app, e.g. /api -> the backend.
CREATE TABLE project_routes (
    id                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id         NUMBER(19) NOT NULL,
    path_prefix        VARCHAR2(100) NOT NULL,
    target_project_id  NUMBER(19) NOT NULL,
    CONSTRAINT fk_routes_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_routes_target FOREIGN KEY (target_project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT uk_routes_project_prefix UNIQUE (project_id, path_prefix)
);
CREATE INDEX ix_routes_target ON project_routes (target_project_id);
