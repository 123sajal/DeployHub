-- Billing: a user's first deployed project is free, redeploys included. Every deploy of another project uses
-- one paid deploy credit; one Razorpay payment buys one credit. Additive only.
ALTER TABLE users ADD (free_project_claimed_at TIMESTAMP(6) WITH TIME ZONE);
ALTER TABLE projects ADD (free_since TIMESTAMP(6) WITH TIME ZONE);

-- Everything created before billing was free, and stays free.
UPDATE projects SET free_since = created_at;
UPDATE users SET free_project_claimed_at = created_at WHERE id IN (SELECT owner_id FROM projects);

-- A Razorpay order (CREATED) that becomes a deploy credit once paid (PAID). The credit is unused while used_at
-- is null; a deploy that fails or is cancelled clears used_at again, so the credit comes back.
CREATE TABLE payments (
    id                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              NUMBER(19) NOT NULL,
    razorpay_order_id    VARCHAR2(40) NOT NULL,
    razorpay_payment_id  VARCHAR2(40),
    amount_paise         NUMBER(10) NOT NULL,
    currency             VARCHAR2(3) NOT NULL,
    status               VARCHAR2(20) NOT NULL,
    created_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    paid_at              TIMESTAMP(6) WITH TIME ZONE,
    used_at              TIMESTAMP(6) WITH TIME ZONE,
    deployment_id        NUMBER(19),
    CONSTRAINT uk_payments_order UNIQUE (razorpay_order_id),
    CONSTRAINT uk_payments_payment UNIQUE (razorpay_payment_id),
    CONSTRAINT ck_payments_status CHECK (status IN ('CREATED', 'PAID')),
    CONSTRAINT fk_payments_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_payments_deployment FOREIGN KEY (deployment_id) REFERENCES deployments (id) ON DELETE SET NULL
);

CREATE INDEX ix_payments_user ON payments (user_id, status);
CREATE INDEX ix_payments_deployment ON payments (deployment_id);
