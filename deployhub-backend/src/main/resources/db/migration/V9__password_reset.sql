-- Forgot password: one-time 6-digit codes sent by email. Additive only.
-- Only a hash of the code is stored. A code works once, for a short time, with a few attempts.
CREATE TABLE password_reset_codes (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     NUMBER(19) NOT NULL,
    code_hash   VARCHAR2(100) NOT NULL,
    attempts    NUMBER(3) DEFAULT 0 NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used_at     TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_reset_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX ix_reset_user ON password_reset_codes (user_id);
