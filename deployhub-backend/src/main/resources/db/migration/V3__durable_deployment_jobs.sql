-- Milestone 4: durable job queue, idempotency keys and deployment status history. Additive only.

-- One job per deployment. Inserted in the same transaction as the deployment, so a committed
-- deployment request can never lose its job (the queue lives in the same database: no outbox needed).
CREATE TABLE deployment_jobs (
    id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deployment_id     NUMBER(19) NOT NULL,
    status            VARCHAR2(20) NOT NULL,
    attempt           NUMBER(10) DEFAULT 0 NOT NULL,
    max_attempts      NUMBER(10) NOT NULL,
    available_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    locked_by         VARCHAR2(100),
    lease_expires_at  TIMESTAMP(6) WITH TIME ZONE,
    last_error        VARCHAR2(1000),
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version           NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT uk_jobs_deployment UNIQUE (deployment_id),
    CONSTRAINT fk_jobs_deployment FOREIGN KEY (deployment_id) REFERENCES deployments (id) ON DELETE CASCADE,
    CONSTRAINT ck_jobs_status CHECK (status IN ('PENDING', 'RUNNING', 'SUCCEEDED', 'FAILED', 'DEAD', 'CANCELLED')),
    CONSTRAINT ck_jobs_attempts CHECK (attempt >= 0 AND max_attempts >= 1)
);

-- Workers look for "PENDING and due" or "RUNNING with an expired lease".
CREATE INDEX ix_jobs_status_available ON deployment_jobs (status, available_at);
CREATE INDEX ix_jobs_status_lease ON deployment_jobs (status, lease_expires_at);

-- Every status change of a deployment: when, why, who (user, worker or system) and on which attempt.
CREATE TABLE deployment_status_history (
    id             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deployment_id  NUMBER(19) NOT NULL,
    from_status    VARCHAR2(20),
    to_status      VARCHAR2(20) NOT NULL,
    reason         VARCHAR2(1000),
    actor          VARCHAR2(120) NOT NULL,
    attempt        NUMBER(10),
    occurred_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_history_deployment FOREIGN KEY (deployment_id) REFERENCES deployments (id) ON DELETE CASCADE
);

CREATE INDEX ix_history_deployment ON deployment_status_history (deployment_id, id);

-- Idempotency-Key header -> the deployment it created. The primary key makes duplicates impossible,
-- even for requests that arrive at the same moment. A separate table (rather than a nullable
-- column with a unique index) because Oracle and H2 treat NULLs in composite unique indexes differently.
CREATE TABLE idempotency_keys (
    user_id        NUMBER(19) NOT NULL,
    idem_key       VARCHAR2(100) NOT NULL,
    request_hash   VARCHAR2(64) NOT NULL,
    deployment_id  NUMBER(19) NOT NULL,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_idempotency_keys PRIMARY KEY (user_id, idem_key),
    CONSTRAINT fk_idem_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_idem_deployment FOREIGN KEY (deployment_id) REFERENCES deployments (id) ON DELETE CASCADE
);

-- Deployments still in progress from before this migration get a job, so they finish instead of hanging.
INSERT INTO deployment_jobs (deployment_id, status, attempt, max_attempts, available_at, created_at, updated_at, version)
SELECT id, 'PENDING', 0, 3, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, 0
FROM deployments WHERE status IN ('QUEUED', 'BUILDING', 'STARTING');

-- Start every existing deployment's history with its current status.
INSERT INTO deployment_status_history (deployment_id, from_status, to_status, reason, actor, occurred_at)
SELECT id, NULL, status, 'Status before history tracking was introduced', 'system', status_changed_at
FROM deployments;
