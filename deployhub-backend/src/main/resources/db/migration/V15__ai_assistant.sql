-- AI assistant, email codes and student discount (ADR 0015). Additive only.

-- What the sign-up assistant collects, and the student check. A student ID photo is never stored: only how and
-- until when the account is a verified student.
ALTER TABLE users ADD (occupation VARCHAR2(20));
ALTER TABLE users ADD (email_verified_at TIMESTAMP(6) WITH TIME ZONE);
ALTER TABLE users ADD (student_verified_until DATE);
ALTER TABLE users ADD (student_verified_by VARCHAR2(20));
ALTER TABLE users ADD CONSTRAINT ck_users_occupation CHECK (occupation IN ('STUDENT', 'PROFESSIONAL'));
ALTER TABLE users ADD CONSTRAINT ck_users_student_proof CHECK (student_verified_by IN ('ID_CARD', 'COLLEGE_EMAIL'));

-- One-time 6-digit codes that prove an email address: before sign-up (no account yet, so no user) and for a
-- college email. Only a hash of the code is stored, as for password reset codes.
CREATE TABLE email_codes (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR2(254) NOT NULL,
    purpose     VARCHAR2(20) NOT NULL,
    user_id     NUMBER(19),
    code_hash   VARCHAR2(100) NOT NULL,
    attempts    NUMBER(3) DEFAULT 0 NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used_at     TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT ck_email_codes_purpose CHECK (purpose IN ('SIGNUP', 'STUDENT')),
    CONSTRAINT fk_email_codes_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX ix_email_codes_email ON email_codes (email, purpose);
-- Every foreign key gets an index (see BUG-17): deleting a user must not lock the whole table.
CREATE INDEX ix_email_codes_user ON email_codes (user_id);

-- AI use per day (India time) and subject ("user:<id>" or "ip:<address>"): the per-user limits and the daily
-- spending cap are counted here. Cost is in thousandths of a paisa, so small calls still add up exactly.
CREATE TABLE assistant_usage (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usage_day        VARCHAR2(10) NOT NULL,
    subject          VARCHAR2(60) NOT NULL,
    requests         NUMBER(10) DEFAULT 0 NOT NULL,
    input_tokens     NUMBER(19) DEFAULT 0 NOT NULL,
    output_tokens    NUMBER(19) DEFAULT 0 NOT NULL,
    cost_millipaise  NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT uq_assistant_usage UNIQUE (usage_day, subject)
);

-- The AI's explanation of a failed deployment, kept so looking at it again costs nothing.
CREATE TABLE deployment_explanations (
    deployment_id  NUMBER(19) PRIMARY KEY,
    explanation    VARCHAR2(4000) NOT NULL,
    model          VARCHAR2(60) NOT NULL,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_explanation_deployment FOREIGN KEY (deployment_id) REFERENCES deployments (id) ON DELETE CASCADE
);
