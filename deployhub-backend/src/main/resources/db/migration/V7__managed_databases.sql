-- One-click databases: a shared MySQL server run by DeployHub, one database + user per project. Additive only.

-- The servers DeployHub manages (one per engine). The admin password is encrypted by the application.
CREATE TABLE database_servers (
    id                        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    engine                    VARCHAR2(20) NOT NULL,
    admin_password_encrypted  VARCHAR2(4000) NOT NULL,
    created_at                TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_db_servers_engine UNIQUE (engine)
);

-- A project's database. Its password is not stored here: it lives (encrypted) in the project's DB_PASSWORD
-- environment variable, which is where the app reads it.
CREATE TABLE project_databases (
    id             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id     NUMBER(19) NOT NULL,
    engine         VARCHAR2(20) NOT NULL,
    database_name  VARCHAR2(64) NOT NULL,
    username       VARCHAR2(32) NOT NULL,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_pdb_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT uk_pdb_project UNIQUE (project_id),
    CONSTRAINT uk_pdb_name UNIQUE (engine, database_name)
);
