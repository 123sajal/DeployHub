package com.deployhub.platform.execution;

import java.util.Comparator;
import java.util.List;
import java.util.regex.Pattern;

/**
 * The nginx configuration of a project's address ("edge"): route prefixes go to other projects' live apps,
 * everything else to the project's own live app. Upstreams are container names on the deployhub network,
 * resolved per request (resolver + variable), so a reload never fails because an app is momentarily gone,
 * and a project without a live app answers 503 instead of an nginx error page.
 */
public final class EdgeConfig {

    /** Port nginx listens on inside its container (unprivileged, so no extra capability is needed). */
    public static final int LISTEN_PORT = 8080;

    /** Same rule as the API validation; anything else could inject nginx syntax. */
    private static final Pattern SAFE_PREFIX = Pattern.compile("^/[A-Za-z0-9._~/-]*$");
    private static final Pattern SAFE_HOST = Pattern.compile("^[a-z0-9-]+$");

    private EdgeConfig() {
    }

    public static String generate(DeploymentExecutor.Gateway gateway) {
        StringBuilder conf = new StringBuilder()
                .append("# Generated by DeployHub for project ").append(gateway.projectId())
                .append(". Rewritten on every deployment; do not edit.\n")
                .append("map $http_upgrade $connection_upgrade { default upgrade; '' close; }\n\n")
                .append("server {\n")
                .append("    listen ").append(LISTEN_PORT).append(";\n")
                .append("    resolver 127.0.0.11 valid=5s ipv6=off;\n")
                .append("    client_max_body_size 25m;\n")
                .append("    proxy_http_version 1.1;\n")
                .append("    proxy_set_header Host $http_host;\n")
                .append("    proxy_set_header X-Real-IP $remote_addr;\n")
                .append("    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n")
                .append("    proxy_set_header X-Forwarded-Proto $scheme;\n")
                .append("    proxy_set_header Upgrade $http_upgrade;\n")
                .append("    proxy_set_header Connection $connection_upgrade;\n")
                .append("    proxy_read_timeout 120s;\n");
        // Longest prefix first is what nginx does anyway for ^~; sorting keeps the file stable and readable.
        List<DeploymentExecutor.Route> routes = gateway.routes().stream()
                .sorted(Comparator.comparing((DeploymentExecutor.Route r) -> r.pathPrefix().length()).reversed()
                        .thenComparing(DeploymentExecutor.Route::pathPrefix))
                .toList();
        for (DeploymentExecutor.Route route : routes) {
            String prefix = normalisePrefix(route.pathPrefix());
            String exact = prefix.substring(0, prefix.length() - 1);
            String target = upstream(route.containerName(), route.port());
            String unavailable = "No live deployment of project " + route.targetName() + " for " + exact;
            conf.append('\n');
            if (!exact.isEmpty()) {
                conf.append(block("location = " + exact, target, unavailable));
            }
            conf.append(block("location ^~ " + prefix, target, unavailable));
        }
        conf.append('\n').append(block("location /", upstream(gateway.containerName(), gateway.port()),
                "No live deployment of project " + gateway.projectName()));
        return conf.append("}\n").toString();
    }

    /** "/api" -> "/api/", "/api/" -> "/api/". */
    static String normalisePrefix(String prefix) {
        if (prefix == null || !SAFE_PREFIX.matcher(prefix).matches() || prefix.equals("/")) {
            throw new IllegalArgumentException("Unsafe route prefix: " + prefix);
        }
        return prefix.endsWith("/") ? prefix : prefix + "/";
    }

    private static String upstream(String containerName, Integer port) {
        if (containerName == null || port == null) {
            return null;
        }
        if (!SAFE_HOST.matcher(containerName).matches()) {
            throw new IllegalArgumentException("Unsafe container name: " + containerName);
        }
        return "http://" + containerName + ":" + port;
    }

    private static String block(String location, String target, String unavailable) {
        if (target == null) {
            return "    " + location + " {\n"
                    + "        default_type text/plain;\n"
                    + "        return 503 \"" + unavailable.replace("\"", "") + "\\n\";\n"
                    + "    }\n";
        }
        return "    " + location + " {\n"
                + "        set $upstream " + target + ";\n"
                + "        proxy_pass $upstream;\n"
                + "    }\n";
    }
}
