package com.deployhub.platform.execution;

import com.deployhub.platform.config.DeployHubProperties;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Component;

import java.time.Duration;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Pattern;

/**
 * Runs the shared MySQL server in Docker and administers it with {@code docker exec ... mysql}.
 *
 * <ul>
 *   <li>Data lives in a named volume, so it survives container restarts and re-creation.</li>
 *   <li>Apps reach it as {@code deployhub-mysql:3306} on the deployhub network; this machine on
 *       {@code 127.0.0.1:<host-port>} (e.g. to create tables). Nothing else can reach it.</li>
 *   <li>Passwords and SQL never appear on a command line: they are passed as {@code -e NAME} with the value in
 *       the docker CLI's own environment. Identifiers are generated by DeployHub and checked against a strict
 *       pattern; passwords are alphanumeric. Nothing user-typed ends up in SQL.</li>
 *   <li>Each project's user gets {@code ALL} on its own database only, so apps can't see each other's data.</li>
 * </ul>
 */
@Slf4j
@Component
public class DockerMysqlServer implements ManagedDatabaseServer {

    private static final Pattern IDENTIFIER = Pattern.compile("^[a-z0-9_]{1,32}$");
    private static final Pattern PASSWORD = Pattern.compile("^[A-Za-z0-9]{12,64}$");
    private static final Duration QUICK = Duration.ofSeconds(60);
    private static final int APP_PORT = 3306;

    private final CommandRunner runner;
    private final DeployHubProperties.Databases settings;
    private final String docker;

    @Autowired
    public DockerMysqlServer(CommandRunner runner, DeployHubProperties properties) {
        this(runner, properties.databases(), properties.execution().dockerCommand());
    }

    DockerMysqlServer(CommandRunner runner, DeployHubProperties.Databases settings, String dockerCommand) {
        this.runner = runner;
        this.settings = settings;
        this.docker = dockerCommand;
    }

    @Override
    public Endpoints endpoints() {
        return new Endpoints(settings.containerName(), APP_PORT, "127.0.0.1", settings.hostPort());
    }

    @Override
    public void ensureRunning(String adminPassword) {
        requirePassword(adminPassword);
        List<String> state = new ArrayList<>();
        boolean exists = run(List.of("container", "inspect", "--format", "{{.State.Running}}", settings.containerName()),
                Map.of(), QUICK, state::add).ok();
        if (!exists) {
            ensureNetwork();
            Map<String, String> env = Map.of("MYSQL_ROOT_PASSWORD", adminPassword);
            CommandRunner.Result created = run(List.of("run", "--detach", "--name", settings.containerName(),
                    "--network", DockerDeploymentExecutor.NETWORK, "--restart", "unless-stopped",
                    "--memory", settings.memory(), "--memory-swap", settings.memory(),
                    "--security-opt", "no-new-privileges",
                    "-e", "MYSQL_ROOT_PASSWORD",
                    "--publish", "127.0.0.1:" + settings.hostPort() + ":" + APP_PORT,
                    "--volume", settings.volume() + ":/var/lib/mysql",
                    "--label", "deployhub.database=mysql",
                    settings.mysqlImage(),
                    // Small footprint: Docker on a laptop has little memory to spare.
                    "--innodb-buffer-pool-size=64M", "--performance-schema=OFF", "--skip-name-resolve"),
                    env, Duration.ofMinutes(10), line -> { });
            requireOk(created, "Starting the MySQL server");
        } else if (state.isEmpty() || !state.getLast().trim().equals("true")) {
            requireOk(run(List.of("start", settings.containerName()), Map.of(), QUICK, line -> { }),
                    "Starting the MySQL server");
        }
        waitUntilReady(adminPassword);
    }

    /**
     * Over TCP on purpose: during its first start MySQL runs a temporary server without networking, which
     * would already answer on the socket and then disappear.
     */
    private void waitUntilReady(String adminPassword) {
        long deadline = System.nanoTime() + settings.startTimeout().toNanos();
        CommandRunner.Result last;
        do {
            last = sql(adminPassword, "SELECT 1");
            if (last.ok()) {
                return;
            }
            sleep(Duration.ofSeconds(2));
        } while (System.nanoTime() < deadline);
        throw new IllegalStateException("The MySQL server did not become ready within "
                + settings.startTimeout().toSeconds() + " s: " + lastLine(last));
    }

    @Override
    public void createDatabase(String adminPassword, String databaseName, String username, String password) {
        requireIdentifier(databaseName);
        requireIdentifier(username);
        requirePassword(password);
        requireOk(sql(adminPassword, "CREATE DATABASE IF NOT EXISTS `" + databaseName
                + "` CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci; "
                + "CREATE USER IF NOT EXISTS '" + username + "'@'%' IDENTIFIED BY '" + password + "'; "
                + "ALTER USER '" + username + "'@'%' IDENTIFIED BY '" + password + "'; "
                + "GRANT ALL PRIVILEGES ON `" + databaseName + "`.* TO '" + username + "'@'%';"),
                "Creating the database");
    }

    @Override
    public void changePassword(String adminPassword, String username, String password) {
        requireIdentifier(username);
        requirePassword(password);
        requireOk(sql(adminPassword, "ALTER USER '" + username + "'@'%' IDENTIFIED BY '" + password + "';"),
                "Changing the database password");
    }

    @Override
    public void dropDatabase(String adminPassword, String databaseName, String username) {
        requireIdentifier(databaseName);
        requireIdentifier(username);
        requireOk(sql(adminPassword, "DROP DATABASE IF EXISTS `" + databaseName + "`; "
                + "DROP USER IF EXISTS '" + username + "'@'%';"), "Deleting the database");
    }

    /** Runs SQL as root inside the server container; password and SQL travel as environment variables. */
    private CommandRunner.Result sql(String adminPassword, String statements) {
        Map<String, String> env = new HashMap<>();
        env.put("MYSQL_PWD", adminPassword);
        env.put("DEPLOYHUB_SQL", statements);
        return run(List.of("exec", "-e", "MYSQL_PWD", "-e", "DEPLOYHUB_SQL", settings.containerName(),
                "sh", "-c", "mysql --protocol=tcp -h127.0.0.1 -uroot -e \"$DEPLOYHUB_SQL\""), env, QUICK, line -> { });
    }

    private void ensureNetwork() {
        if (run(List.of("network", "inspect", DockerDeploymentExecutor.NETWORK), Map.of(), QUICK, line -> { }).ok()) {
            return;
        }
        CommandRunner.Result create = run(List.of("network", "create", "--label", "deployhub=true",
                DockerDeploymentExecutor.NETWORK), Map.of(), QUICK, line -> { });
        if (!create.ok() && !create.tailText().contains("already exists")) {
            throw new IllegalStateException("Creating the deployhub network failed: " + lastLine(create));
        }
    }

    private CommandRunner.Result run(List<String> args, Map<String, String> env, Duration timeout,
                                     java.util.function.Consumer<String> onLine) {
        List<String> command = new ArrayList<>();
        command.add(docker);
        command.addAll(args);
        try {
            return runner.run(command, env, null, timeout, null, onLine);
        } catch (CommandRunner.StartException e) {
            throw new IllegalStateException("The docker command was not found. Is Docker Desktop installed?", e);
        }
    }

    private static void requireOk(CommandRunner.Result result, String what) {
        if (!result.ok()) {
            String reason = lastLine(result);
            if (reason.toLowerCase(java.util.Locale.ROOT).contains("cannot connect to the docker daemon")) {
                reason = "Docker is not running. Start Docker Desktop and try again.";
            }
            throw new IllegalStateException(what + " failed: " + reason);
        }
    }

    private static String lastLine(CommandRunner.Result result) {
        for (int i = result.tail().size() - 1; i >= 0; i--) {
            String line = result.tail().get(i).trim();
            if (!line.isEmpty()) {
                return line.length() > 500 ? line.substring(0, 500) + "..." : line;
            }
        }
        return result.timedOut() ? "timed out" : "no output";
    }

    private static void requireIdentifier(String value) {
        if (value == null || !IDENTIFIER.matcher(value).matches()) {
            throw new IllegalArgumentException("Unsafe database identifier: " + value);
        }
    }

    private static void requirePassword(String value) {
        if (value == null || !PASSWORD.matcher(value).matches()) {
            throw new IllegalArgumentException("Database passwords must be 12-64 letters and digits");
        }
    }

    private static void sleep(Duration duration) {
        try {
            Thread.sleep(duration);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new IllegalStateException("Interrupted while waiting for MySQL", e);
        }
    }
}
